import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { readPythonInventory } from "../src/inventory/python";
import { directoryTree } from "../src/inventory/tree";

/** A temporary repository from a map of files. */
function repo(files: Record<string, string>) {
  const dir = mkdtempSync(join(tmpdir(), "teire-py-readers-"));
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), text);
  }
  return dir;
}

describe("Python manifests beyond pyproject and a root requirements file (S18)", () => {
  const dirs: string[] = [];
  afterAll(() => {
    for (const d of dirs) rmSync(d, { recursive: true, force: true });
  });
  const read = async (files: Record<string, string>) => {
    const dir = repo(files);
    dirs.push(dir);
    return readPythonInventory(dir, directoryTree(dir));
  };
  const of = (projects: Awaited<ReturnType<typeof read>>, name: string) =>
    projects.flatMap((p) => p.instances).filter((i) => i.name === name);

  it("pins each pip-tools .in from its own compiled .txt (D-19)", async () => {
    const projects = await read({
      "requirements/base.in": "requests>=2\n",
      "requirements/base.txt": "# autogenerated by pip-compile\nrequests==2.31.0\n",
      "requirements/dev.in": "-r base.in\npytest\n",
      "requirements/dev.txt": "# autogenerated by pip-compile\nrequests==2.31.0\npytest==8.1.1\n",
    });
    expect(of(projects, "requests")[0]).toMatchObject({
      version: "2.31.0",
      lockfilePath: "requirements/base.txt",
    });
    expect(of(projects, "pytest")[0]).toMatchObject({
      version: "8.1.1",
      lockfilePath: "requirements/dev.txt",
    });
  });

  it("reads setup.cfg, and setup.py statically, never running it (D-20)", async () => {
    const cfg = await read({
      "setup.cfg":
        "[options]\ninstall_requires =\n    httpx>=0.24\n    pydantic>=1.10,<2\n\n[options.extras_require]\ncli = click>=8\n",
    });
    expect(of(cfg, "httpx")[0]).toMatchObject({
      declaredRange: ">=0.24",
      scope: "prod",
      manifestPath: "setup.cfg",
    });
    expect(of(cfg, "click")[0]?.scope).toBe("optional");
    const py = await read({
      "setup.py":
        'import os\nos.system("echo never")\nfrom setuptools import setup\nsetup(name="x", install_requires=["flask>=2.0", "sqlalchemy<2"], extras_require={"dev": ["black"]})\n',
    });
    expect(of(py, "flask")[0]).toMatchObject({ declaredRange: ">=2.0", manifestPath: "setup.py" });
    expect(of(py, "sqlalchemy")[0]?.declaredRange).toBe("<2");
    expect(of(py, "black")[0]?.scope).toBe("optional");
  });

  it("keeps setup.cfg markers and a -r'd file's own scope (S18 review R1, R2)", async () => {
    const cfg = await read({
      "setup.cfg":
        '[options]\ninstall_requires =\n    importlib-metadata; python_version<"3.8"\n    httpx>=0.24\n',
    });
    expect(of(cfg, "importlib-metadata")[0]?.environment).toEqual({ markers: 'python_version < "3.8"' });
    expect(of(cfg, "httpx")[0]?.environment).toBeUndefined();
    const reqs = await read({
      "requirements.txt": "flask==3.0.0\n",
      "requirements-dev.txt": "-r requirements.txt\npytest==8.0.0\n",
    });
    expect(of(reqs, "flask").map((i) => i.scope)).toEqual(["prod"]);
    expect(of(reqs, "pytest")[0]?.scope).toBe("dev");
  });

  it("reads a project in a build/ folder, never build output (D-21)", async () => {
    const projects = await read({
      "packages/build/pyproject.toml": '[project]\nname = "build-tools"\ndependencies = ["jinja2>=3"]\n',
      "build/lib/requirements.txt": "flask==0.1\n",
    });
    expect(of(projects, "jinja2")[0]?.manifestPath).toBe("packages/build/pyproject.toml");
    expect(of(projects, "flask")).toEqual([]);
  });

  it("follows PEP 735 include-group and reads a Poetry list of constraints (D-32)", async () => {
    const projects = await read({
      "pyproject.toml": `[project]
name = "x"
dependencies = []

[dependency-groups]
test = ["pytest>=8"]
dev = [{ include-group = "test" }, "ruff"]

[tool.poetry.dependencies]
python = "^3.9"
numpy = [
  { version = "^1.24", python = "<3.12" },
  { version = "^2.0", python = ">=3.12" },
]
`,
    });
    expect(of(projects, "pytest").length).toBeGreaterThan(0);
    expect(of(projects, "ruff").length).toBeGreaterThan(0);
    // Read for Python 3.12: only the constraint that applies there is in force.
    const numpy = of(projects, "numpy");
    expect(numpy.find((i) => !i.environment?.markers)?.declaredRange).toBe("^2.0");
    expect(numpy.find((i) => i.environment?.markers)?.declaredRange).toBe("^1.24");
  });
});
